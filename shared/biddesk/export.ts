import type { Deadline, FitResult, Opportunity } from "./types";

export interface Packet { opportunity: Opportunity; fit: FitResult; statement: string; outline: string; deadlines: Deadline[] }

/** Bid packet as one Markdown document. */
export function packetMarkdown(p: Packet, generatedAt = new Date()): string {
  const o = p.opportunity;
  return [
    `# Bid Packet — ${o.title}`, "",
    `- **Solicitation:** ${o.solicitationNumber} (${o.type})`, `- **Agency:** ${o.agency}${o.office ? ` / ${o.office}` : ""}`,
    `- **Response due:** ${o.responseDeadline}`, `- **SAM.gov:** ${o.url}`, "",
    `## Fit: ${p.fit.score}/100 — ${p.fit.verdict}`, "",
    ...p.fit.factors.map((f) => `- ${f.name} (${f.weight}%): ${Math.round(f.score * 100)}% — ${f.evidence}`),
    ...(p.fit.missing.length ? ["", `**Gaps:** ${p.fit.missing.join(", ")}`] : []), "",
    `## Deadlines`, "", ...p.deadlines.map((d) => `- [${d.status}] ${d.label}: ${d.at}`), "",
    p.statement.trim(), "", p.outline.trim(), "",
    `---`, `_Generated by Bid Desk ${generatedAt.toISOString()} (rule-based; review before submitting)._`, "",
  ].join("\n");
}

/** Minimal dependency-free PDF (Helvetica, Letter, wrapped lines, multi-page). Markdown marks are flattened. */
export function markdownToPdf(md: string): Uint8Array {
  const plain = md.split("\n").map((l) => l.replace(/^#+\s*/, "").replace(/\*\*|__|`/g, "").replace(/^\|?-{3,}.*$/, "").replace(/[^\x20-\x7E]/g, (c) => ({ "—": "-", "–": "-", "•": "*", "’": "'", "“": '"', "”": '"' } as Record<string, string>)[c] ?? "?"));
  const lines: string[] = [];
  for (const l of plain) { let s = l; if (!s) { lines.push(""); continue; } while (s.length > 95) { const cut = s.lastIndexOf(" ", 95) > 40 ? s.lastIndexOf(" ", 95) : 95; lines.push(s.slice(0, cut)); s = s.slice(cut).trimStart(); } lines.push(s); }
  const per = 56, pages: string[][] = [];
  for (let i = 0; i < Math.max(lines.length, 1); i += per) pages.push(lines.slice(i, i + per));
  const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  const objs: string[] = [];
  const n = pages.length; // ids: 1 catalog, 2 pages, 3 font, then (page, content) pairs
  objs[1] = `<< /Type /Catalog /Pages 2 0 R >>`;
  objs[2] = `<< /Type /Pages /Count ${n} /Kids [${pages.map((_, i) => `${4 + i * 2} 0 R`).join(" ")}] >>`;
  objs[3] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>`;
  pages.forEach((pg, i) => {
    const stream = `BT /F1 10 Tf 13 TL 50 750 Td ${pg.map((l) => `(${esc(l)}) '`).join(" ")} ET`;
    objs[4 + i * 2] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents ${5 + i * 2} 0 R >>`;
    objs[5 + i * 2] = `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`;
  });
  let out = "%PDF-1.4\n"; const xref: number[] = [];
  for (let i = 1; i < objs.length; i++) { xref[i] = out.length; out += `${i} 0 obj\n${objs[i]}\nendobj\n`; }
  const x = out.length;
  out += `xref\n0 ${objs.length}\n0000000000 65535 f \n${xref.slice(1).map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("")}trailer\n<< /Size ${objs.length} /Root 1 0 R >>\nstartxref\n${x}\n%%EOF\n`;
  return new TextEncoder().encode(out);
}
